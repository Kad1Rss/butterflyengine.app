let currentLang = "en";
function t(key) { return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key; }

function applyLanguage(lang, persist) {
  currentLang = lang === "tr" ? "tr" : "en";
  document.documentElement.lang = currentLang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-set-lang]").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-set-lang") === currentLang);
  });
  document.title = currentLang === "tr"
    ? "Butterfly Story Factory — Yerel yapay zekâ belgesel video stüdyosu"
    : "Butterfly Story Factory — Local AI Documentary Video Studio";
  const desc = document.querySelector('meta[name="description"]');
  if (desc) {
    desc.setAttribute("content", currentLang === "tr"
      ? "Tek fikirden senaryolu, seslendirmeli, altyazılı 1080p belgesel ve dikey Reels üretin — tamamen Windows bilgisayarınızda. 24 dil, 3–12 dakika, abonelik yok."
      : "Turn one idea into a scripted, narrated, subtitled 1080p documentary and vertical Reels — entirely on your Windows PC. 24 languages, 3–12 minutes, no subscription.");
  }
  if (persist) {
    try { localStorage.setItem("butterfly_lang", currentLang); } catch (e) {}
    const url = new URL(window.location.href);
    if (currentLang === "tr") url.searchParams.set("lang", "tr"); else url.searchParams.delete("lang");
    history.replaceState(null, "", url.pathname + (url.search ? url.search : "") + url.hash);
  }
}

function renderChips() {
  const ui = document.getElementById("uiChips");
  const content = document.getElementById("contentChips");
  if (ui) ui.innerHTML = UI_LANGS.map(([name, code], i) => `<span class="chip${i < 4 ? " hot" : ""}">${name} <span style="opacity:.55">${code}</span></span>`).join("");
  if (content) content.innerHTML = CONTENT_LANGS.map((name, i) => `<span class="chip${i < 4 ? " hot" : ""}">${name}</span>`).join("") + '<span class="chip hot">+ custom BCP-47</span>';
}

function setupGallery() {
  const main = document.getElementById("galleryMain");
  document.querySelectorAll("[data-gallery]").forEach(btn => {
    btn.addEventListener("click", () => {
      if (!main) return;
      main.src = btn.getAttribute("data-gallery");
    });
  });
}

function setupReveal() {
  const items = document.querySelectorAll(".reveal");
  if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    items.forEach(el => el.classList.add("in"));
    return;
  }
  const io = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) { entry.target.classList.add("in"); io.unobserve(entry.target); }
    });
  }, { threshold: 0.12 });
  items.forEach(el => io.observe(el));
}

function setupMobileMenu() {
  const btn = document.getElementById("mobileMenu");
  const nav = document.getElementById("navLinks");
  if (!btn || !nav) return;
  btn.addEventListener("click", () => nav.classList.toggle("open"));
  nav.querySelectorAll("a").forEach(a => a.addEventListener("click", () => nav.classList.remove("open")));
}

function initialLanguage() {
  try {
    const stored = localStorage.getItem("butterfly_lang");
    if (stored === "tr" || stored === "en") return stored;
  } catch (e) {}
  const param = new URLSearchParams(window.location.search).get("lang");
  if (param === "tr") return "tr";
  if (param === "en") return "en";
  return (navigator.language || "").toLowerCase().startsWith("tr") ? "tr" : "en";
}

document.addEventListener("DOMContentLoaded", () => {
  renderChips();
  setupGallery();
  setupReveal();
  setupMobileMenu();
  document.querySelectorAll("[data-set-lang]").forEach(btn => {
    btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-set-lang"), true));
  });
  applyLanguage(initialLanguage(), false);
});
